"""Pixel-art source for the 新郎 Groom bead pattern (MARD 221 palette).

Painted region by region so the geometry stays readable and tweakable.
Canvas is 42 x 41 — the same board as the matching 新娘 Bride chart, so the
pair hangs at identical bead scale (head = 31 rows tall in both).
"""

